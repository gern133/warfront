import { SAM_RANGE } from './sam';
import { dpow } from '../fixmath';

// --- Завод (клавиша 2) ---
// Добывает золото на суше и ускоряет пополнение армии в своём радиусе. Радиус —
// как у ПВО. Постройка 10с, апгрейд мгновенный и бесконечный (как у городов).
export const FACTORY_BUILD_TICKS = 100; // 10с на постройку
export const FACTORY_RANGE = SAM_RANGE; // радиус зоны действия (усиление + дороги)

// Цена «в общем» по суммарному уровню всех заводов. Было 125к, 250к, 500к и дальше
// ПЛОСКИЙ 1млн — та же болезнь, что была у ПВО: заводов не могло быть много, а
// значит и экономики на них не построить. Теперь кривая растёт плавно.
const FACTORY_COSTS = [125_000, 200_000, 300_000, 450_000, 650_000, 900_000, 1_200_000];
export function factoryCost(ownedLevels: number): number {
  return FACTORY_COSTS[Math.min(Math.max(0, ownedLevels), FACTORY_COSTS.length - 1)];
}

// Доход завода за тик. Раньше было 8 + level·2 — и эта функция вообще нигде не
// вызывалась, то есть заводы «добывали золото» только на словах. При подключении
// выяснилось, что масштаб не тот: 10–50 монет за тик против построек по 50 000 и
// выше — доли процента дохода. Теперь доход соизмерим с ценами: завод 1-го уровня
// окупается примерно за 2 минуты, а рост дохода опережает линейный, чтобы апгрейд
// за 1 млн имел смысл.
export function factoryIncome(level: number): number {
  return Math.round(50 * dpow(level, 1.5));
}

// ускорение регена: базово +10%, +3% за каждые 10 уровней; действует на первые
// 30к войск на каждый завод (у больших армий буст слабее)
export function factoryBoostPct(level: number): number {
  return 0.1 + 0.03 * Math.floor(level / 10);
}
// Выплата грузовика за посещённое здание растёт с уровнем завода: +10% за уровень,
// без потолка. Раньше она была плоской (TRUCK_REWARD), и завод 30-го уровня возил
// ровно столько же золота, сколько только что построенный, — прокачка добавляла
// только пассивный factoryIncome и радиус усиления.
export const TRUCK_REWARD_PER_LEVEL = 0.1;
export function truckReward(base: number, level: number): number {
  return Math.round(base * dpow(1 + TRUCK_REWARD_PER_LEVEL, Math.max(1, level) - 1));
}

export const FACTORY_COVER = 30000; // войск, которые «покрывает» один завод
