// Местность в бою. Массив `terrain[]` хранит тип клетки: 0 вода, 1 трава,
// 2 песок, 3 камень, 4 снег (см. T_* в server/map/earthmap.ts) — и на карте
// Земли, и на случайной (genTerrain классифицирует шумом). До этого геймплей
// проверял только «суша/вода», а тип использовался лишь для отрисовки.
//
// Как в OpenFront, местность даёт ДВА множителя: цену клетки в войсках и расход
// квоты захвата (темп). Камень/снег — естественная линия обороны, песок —
// коридор для быстрого наступления.

// Множитель ЦЕНЫ клетки (войск за захват). Выкл: [0, 1, 1, 1, 1]
export const TERRAIN_DEF = [0, 1, 0.85, 1.5, 1.3];

// Множитель РАСХОДА КВОТЫ на клетку (темп захвата). Выкл: [0, 1, 1, 1, 1]
export const TERRAIN_SPEED = [0, 1, 0.85, 1.6, 1.35];

// Самая дешёвая местность — ниже этой доли базовой цены клетка стоить не может.
// Нужно, чтобы «наступление выдохлось» проверялось по реально минимальной цене.
export const TERRAIN_DEF_MIN = Math.min(...TERRAIN_DEF.slice(1));

// Очередь по местности внутри одной корзины фронта: наступление сначала берёт
// удобные клетки (песок), потом обычные, горы/снег — последними. Так фронт
// обтекает рельеф вместо лба в гору. Выкл: [0, 0, 0, 0, 0] (одна очередь).
export const TERRAIN_TIER = [0, 1, 0, 2, 2];
export const TERRAIN_TIERS = Math.max(...TERRAIN_TIER) + 1;
