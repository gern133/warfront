// Сеяный генератор случайных чисел для СИМУЛЯЦИИ. Аналог PseudoRandom из OpenFront.
//
// Зачем: пока симуляция зовёт Math.random(), она невоспроизводима — один и тот же
// ход событий нельзя повторить. Это мешает двум разным вещам:
//
//  1. Замерам баланса. Любое сравнение «до/после» шумит, потому что партии разные:
//     приходится гонять по три прогона и всё равно спорить, шум это или эффект.
//  2. Модели lockstep (как у OpenFront), где сервер рассылает только команды
//     игроков, а симуляцию считает КАЖДЫЙ клиент у себя. Она требует, чтобы
//     одинаковые входные данные давали побитово одинаковый результат.
//
// Алгоритм — xorshift32 на ЦЕЛЫХ числах: одинаков на любом движке, потому что
// целочисленные побитовые операции в JS определены строго. Деление на 2^32 для
// получения дроби тоже точно: степень двойки представима в double без потерь.
export class Rng {
  private s: number;

  constructor(seed: number) {
    // ноль — вырожденное состояние xorshift (из него не выйти), поэтому подменяем
    this.s = (seed >>> 0) || 0x9e3779b9;
  }

  /** Следующее 32-битное беззнаковое. */
  next(): number {
    let x = this.s;
    x ^= x << 13;
    x >>>= 0;
    x ^= x >>> 17;
    x ^= x << 5;
    x >>>= 0;
    this.s = x;
    return x;
  }

  /** Дробь в [0, 1). Замена Math.random(). */
  float(): number {
    return this.next() / 4294967296;
  }

  /** Целое в [0, n). Замена (Math.random() * n) | 0. */
  int(n: number): number {
    if (n <= 0) return 0;
    return this.next() % n;
  }

  /** Событие с вероятностью p. */
  chance(p: number): boolean {
    return this.float() < p;
  }

  /** Случайный элемент массива (undefined для пустого). */
  pick<T>(arr: readonly T[]): T | undefined {
    return arr.length ? arr[this.int(arr.length)] : undefined;
  }

  /** Текущее состояние — чтобы сохранить/восстановить ход генератора. */
  state(): number {
    return this.s;
  }

  setState(s: number) {
    this.s = (s >>> 0) || 0x9e3779b9;
  }
}
