/**
 * Суммарная цена следующих `count` шагов подряд.
 *
 * Считать `цена × count` нельзя: у порта, города, завода, ПВО и штаба цена зависит
 * от того, сколько уже построено, и растёт с каждым шагом. Например пять портов с
 * нуля стоят 200к + 250к + 500к + 1млн + 1млн, а не 200к × 5.
 */
export function batchCost(
  step: (n: number) => number,
  from: number,
  count: number
): number {
  let total = 0;
  for (let i = 0; i < count; i++) total += step(from + i);
  return total;
}

