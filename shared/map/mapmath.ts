function rowLat(y: number, h: number): number {
  return LAT_TOP - ((y + 0.5) / h) * LAT_SPAN;
}

function latRow(lat: number, h: number): number {
  return Math.floor(((LAT_TOP - lat) / LAT_SPAN) * h);
}

