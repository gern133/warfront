// Территория в войсках: сколько «эффективных» клеток идёт в потолок армии.
export function cellFactor(cells: number): number {
  return cells <= CAP_KNEE ? cells : CAP_KNEE * Math.pow(cells / CAP_KNEE, CAP_EXP);
}

