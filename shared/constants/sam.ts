import { HQ_EXPLODE_RADIUS } from './hq';

// --- ПВО (зенитно-ракетный комплекс), клавиша 6 ---
// Сбивает вражеские ядерные ракеты, чья цель попадает в радиус действия.
// Уровень = сколько ракет можно перехватить до перезарядки; каждый заряд
// восстанавливается параллельно за 7с.
export const SAM_BUILD_TICKS = 50; // 5с на постройку/апгрейд
export const SAM_RELOAD_TICKS = 70; // 7с на восстановление одного заряда
// радиус действия — втрое больше радиуса ядерного взрыва (HQ_EXPLODE_RADIUS*2)
export const SAM_RANGE = HQ_EXPLODE_RADIUS * 6;

// Цена «в общем» по суммарному уровню всех твоих ПВО. Раньше было 1.5млн за первое
// и ПЛОСКИЕ 3млн за каждое следующее — из-за этого покрыть территорию ПВО не мог
// никто: 4 установки стоили 10.5млн, 8 — 22.5млн, 16 — 46.5млн, а вся заработанная
// ботом за партию сумма — порядка 6.5млн. Для сравнения город и порт стоят 50–250к,
// то есть ПВО было дороже любой другой постройки в 10–60 раз.
// Теперь цена ПРОГРЕССИВНАЯ, как у портов и городов: покрытие площади доступно, а
// глубина (высокие уровни перехвата) остаётся дорогой.
const SAM_COSTS = [400_000, 600_000, 800_000, 1_000_000, 1_500_000, 2_000_000, 3_000_000];
export function samCost(ownedLevels: number): number {
  return SAM_COSTS[Math.min(Math.max(0, ownedLevels), SAM_COSTS.length - 1)];
}
